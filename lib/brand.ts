/** 성별 점 색. gender 값이 'female' | 'F' | '여' 로 섞여 들어와서 한 곳에서 흡수한다. */
export const genderColor = (gender: string | null | undefined, dark: boolean) =>
  GENDER_COLORS[dark ? 'dark' : 'light'][
    gender === 'female' || gender === 'F' || gender === '여' ? 'female' : 'male'
  ];

